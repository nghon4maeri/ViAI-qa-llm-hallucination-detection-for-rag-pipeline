# applications/api/backend/app/evaluation/schemas.py
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field, field_validator


class EvaluationInput(BaseModel):
    context: str = Field(..., min_length=1, max_length=15000, description="Reference context")
    prompt: str = Field(..., min_length=1, max_length=2000, description="User question / prompt")
    response: str = Field(..., min_length=1, max_length=5000, description="AI-generated response")


class EvaluationBreakdown(BaseModel):
    """
    Detailed explainability metrics.
    Fields are Optional so that unavailable metrics are honestly represented as None
    instead of substituting deceptive default/placeholder values.
    """
    p_entailment: Optional[float] = Field(None, description="DeBERTa NLI Entailment probability")
    p_neutral: Optional[float] = Field(None, description="DeBERTa NLI Neutral probability")
    p_contradiction: Optional[float] = Field(None, description="DeBERTa NLI Contradiction probability")
    new_entity_count: Optional[int] = Field(None, description="Count of entities in response not found in context")
    new_entities: Optional[List[str]] = Field(None, description="List of novel entities extracted from response")
    entity_overlap_ratio: Optional[float] = Field(None, description="Overlap ratio between context and response entities")
    vistral_extrinsic_prob: Optional[float] = Field(None, description="Qwen/Vistral zero-shot extrinsic probability")
    active_guardrail: Optional[str] = Field(None, description="Triggered safety guardrail rule name, if any")


class EvaluationResult(BaseModel):
    label: str = Field(..., description="Verdict: 'no', 'intrinsic', or 'extrinsic'")
    confidence: float = Field(..., ge=0.0, le=1.0, description="Prediction confidence score")
    breakdown: EvaluationBreakdown = Field(default_factory=EvaluationBreakdown)
    model_version: str = Field(default="vihallu-v2-hybrid")


class RagEvaluationInput(BaseModel):
    """One RAG turn: the question, the chunks the retriever returned, and the generated answer."""
    question: str = Field(..., min_length=1, max_length=2000, description="User question sent to the RAG pipeline")
    contexts: List[str] = Field(..., min_length=1, max_length=20, description="Retrieved chunks, in retrieval order")
    answer: str = Field(..., min_length=1, max_length=5000, description="Answer generated by the RAG pipeline")
    ground_truth: Optional[str] = Field(None, max_length=5000, description="Reference answer; enables context_recall")

    @field_validator("contexts")
    @classmethod
    def validate_contexts(cls, v: List[str]) -> List[str]:
        chunks = [c.strip() for c in v if c and c.strip()]
        if not chunks:
            raise ValueError("contexts must contain at least one non-empty chunk")
        if any(len(c) > 15000 for c in chunks):
            raise ValueError("each context chunk must be at most 15000 characters")
        return chunks


class ClaimVerdict(BaseModel):
    text: str = Field(..., description="Answer sentence evaluated as one claim")
    label: str = Field(..., description="Verdict for this claim: 'no', 'intrinsic', or 'extrinsic'")
    confidence: float = Field(..., ge=0.0, le=1.0)
    context_index: int = Field(..., ge=0, description="Index of the chunk the verdict was taken from (supporting chunk when label is 'no')")
    breakdown: EvaluationBreakdown = Field(default_factory=EvaluationBreakdown)


class RagMetrics(BaseModel):
    """
    Retrieval/answer quality signals. None means the metric could not be computed
    (no ground_truth, or an engine without embeddings), never a placeholder.
    Relevance scores are PhoBERT cosines: comparable across runs, not calibrated probabilities.
    """
    answer_relevance: Optional[float] = Field(None, description="Cosine(question, answer)")
    context_relevance: Optional[List[float]] = Field(None, description="Cosine(question, chunk) per retrieved chunk")
    context_utilization: float = Field(..., ge=0.0, le=1.0, description="Share of chunks that support at least one answer claim")
    context_recall: Optional[float] = Field(None, ge=0.0, le=1.0, description="Share of ground_truth sentences supported by the chunks")


class RagEvaluationResult(BaseModel):
    label: str = Field(..., description="Overall verdict: 'no' only when every claim is supported")
    confidence: float = Field(..., ge=0.0, le=1.0)
    faithfulness: float = Field(..., ge=0.0, le=1.0, description="Share of claims supported by the retrieved contexts")
    claims: List[ClaimVerdict]
    metrics: RagMetrics
    model_version: str


class ToolCallTrace(BaseModel):
    name: str
    input: Dict[str, Any]
    output: Any
    latency_ms: float


class JudgeClaim(BaseModel):
    index: int = Field(..., description="Index into the Tier 1 claims list")
    label: str = Field(..., description="'no', 'intrinsic' or 'extrinsic'")
    reason: str = Field(..., description="Why, in Vietnamese, citing the evidence")
    evidence_index: Optional[int] = Field(None, description="Chunk that supports or contradicts the claim")
    agrees_with_tier1: bool


class JudgeVerdict(BaseModel):
    """Tier 2 result. status != 'completed' means the agent gave no verdict and Tier 1 stands."""
    status: str = Field(..., description="completed | refused | incomplete")
    label: Optional[str] = None
    faithfulness: Optional[float] = None
    explanation: Optional[str] = None
    claims: List[JudgeClaim] = Field(default_factory=list)
    tool_calls: List[ToolCallTrace] = Field(default_factory=list)
    model: str
    input_tokens: int = 0
    output_tokens: int = 0
    latency_ms: float = 0.0
